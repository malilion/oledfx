import { encodeSequence } from '../src/core/xor-rle.js';
import { validateSequence } from './sequence.mjs';

export function buildHeader(sequence, symbol = 'oledfx_animation') {
  validateSequence(sequence);
  if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(symbol)) throw new Error('Symbol must be a C identifier beginning with a letter');
  const { width = 128, height = 64, fps = 16, frames } = sequence;
  const encoded = encodeSequence(frames), offsets = [0];
  for (const frame of encoded) offsets.push(offsets.at(-1) + frame.length);
  const data = Uint8Array.from(encoded.flatMap(frame => Array.from(frame)));
  const sizes = encoded.map(frame => frame.length), prefix = symbol.toUpperCase();
  const storageBytes = data.length + 4 * (offsets.length + sizes.length);
  const array = (type, name, values, hex = false) => {
    const rows = [];
    for (let i = 0; i < values.length; i += 16)
      rows.push('  ' + Array.from(values.slice(i, i + 16), value => hex ? `0x${value.toString(16).padStart(2, '0')}` : String(value)).join(', '));
    return `static const ${type} ${symbol}_${name}[] PROGMEM = {\n${rows.join(',\n')}\n};\n`;
  };
  const header = `/* Generated by oledfx. SSD1306 vertical pages; decode in frame order.
 * Start with a zeroed framebuffer; reset before replaying frame 0. */
#ifndef ${prefix}_H
#define ${prefix}_H
#include <stdint.h>
#ifdef __AVR__
#include <avr/pgmspace.h>
#endif
#ifndef PROGMEM
#define PROGMEM
#endif
#define ${prefix}_WIDTH ${width}
#define ${prefix}_HEIGHT ${height}
#define ${prefix}_PAGE_COUNT ${height / 8}
#define ${prefix}_FRAME_BYTES ${width * height / 8}
#define ${prefix}_FRAME_COUNT ${frames.length}
#define ${prefix}_FPS ${fps}
#define ${prefix}_DATA_BYTES ${data.length}
#define ${prefix}_STORAGE_BYTES ${storageBytes}

${array('uint8_t', 'data', data, true)}
${array('uint32_t', 'offsets', offsets)}
${array('uint32_t', 'sizes', sizes)}
#endif
`;
  return { header, data, offsets, sizes, encoded, storageBytes };
}

export const decoderSource = `/* oledfx XOR-RLE: persistent SSD1306 page-packed buffer; no allocation.
 * Zero buffer before frame 0. Reset before replay; feed frames in order.
 * AVR: read header offsets/sizes with pgm_read_dword; byte reads below
 * use pgm_read_byte. ESP32/host use normal memory-mapped flash reads. */
#include <stddef.h>
#include <stdint.h>
#ifdef __AVR__
#include <avr/pgmspace.h>
#endif
#ifndef OLEDFX_READ_BYTE
#ifdef __AVR__
#define OLEDFX_READ_BYTE(p) pgm_read_byte(p)
#else
#define OLEDFX_READ_BYTE(p) (*(p))
#endif
#endif

int oledfx_xor_rle_decode(uint8_t *frame, size_t frame_size,
                         const uint8_t *src, size_t src_size) {
  size_t i = 0, pos = 0, n, j;
  uint8_t token;
  if (!frame || !src) return 0;
  /* Validate first, so malformed input cannot partially mutate the frame. */
  while (i < src_size) {
    token = OLEDFX_READ_BYTE(src + i++);
    n = (token & 127u) + 1u;
    if (n > frame_size - pos) return 0;
    if (token & 128u) {
      if (n > src_size - i) return 0;
      i += n;
    }
    pos += n;
  }
  if (pos != frame_size) return 0;
  i = 0; pos = 0;
  while (i < src_size) {
    token = OLEDFX_READ_BYTE(src + i++);
    n = (token & 127u) + 1u;
    if (token & 128u)
      for (j = 0; j < n; ++j) frame[pos + j] ^= OLEDFX_READ_BYTE(src + i++);
    pos += n;
  }
  return 1;
}
`;
