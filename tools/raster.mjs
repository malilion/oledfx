export function drawText(frame, text, x, y, color, scale = 1) {
  for (const char of text) {
    const glyph = rows[char] ?? rows[char.toUpperCase()] ?? rows[' '];
    for (let gy = 0; gy < 7; gy++) for (let gx = 0; gx < 5; gx++) {
      if (glyph[gy][gx] !== '1') continue;
      for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) {
        setPixel(frame, x + gx * scale + sx, y + gy * scale + sy, color);
      }
    }
    x += 6 * scale;
  }
}
