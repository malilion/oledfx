export function makeRGBA(width, height, color = [9, 14, 22, 255]) {
  const data = new Uint8ClampedArray(width * height * 4);
  for (let i = 0; i < data.length; i += 4) data.set(color, i);
  return { width, height, data };
}
export function setPixel(frame, x, y, color) {
  if (x < 0 || y < 0 || x >= frame.width || y >= frame.height) return;
  frame.data.set(color, (y * frame.width + x) * 4);
}
export function blit(target, source, x, y) {
  for (let row = 0; row < source.height; row++)
    target.data.set(source.data.subarray(row * source.width * 4, (row + 1) * source.width * 4), ((y + row) * target.width + x) * 4);
}

