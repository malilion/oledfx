import { encodeSequence } from './xor-rle.js';
import { validateSequence } from './sequence.js';
import { getPixel } from './framebuffer.js';
import { playerSource } from './mcu-player.js';

function validateSymbol(symbol) {
  if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(symbol)) throw new Error('Symbol must be a C identifier beginning with a letter');
}

// Mode B uses horizontal rows, unlike SSD1306's vertical page layout.
// XBM is LSB-first; Adafruit drawBitmap is MSB-first. Each row is padded.
export function packBitmap(frame, width, height, format) {
  if (!['u8g2', 'adafruit'].includes(format)) throw new RangeError(`Unknown bitmap format: ${format}`);
  const stride = Math.ceil(width / 8), data = new Uint8Array(stride * height);
  const fb = { width, height, data: frame };
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    if (getPixel(fb, x, y)) data[y * stride + (x >> 3)] |= 1 << (format === 'u8g2' ? x & 7 : 7 - (x & 7));
  }
  return data;
}

export function buildBitmapHeader(sequence, symbol = 'oledfx_animation', format = 'u8g2') {
  const { width, height, fps, frames } = validateSequence(sequence);
  validateSymbol(symbol);
  const prefix = symbol.toUpperCase(), frameBytes = Math.ceil(width / 8) * height;
  const data = Uint8Array.from(frames.flatMap(frame => Array.from(packBitmap(frame, width, height, format))));
  const rows = [];
  for (let i = 0; i < data.length; i += 16) rows.push('  ' + Array.from(data.slice(i, i + 16), v => `0x${v.toString(16).padStart(2, '0')}`).join(', '));
  const header = `/* Generated by oledfx: ${format}, horizontal rows, ${format === 'u8g2' ? 'LSB' : 'MSB'} first.
 * Random-access frames. Use ${symbol}_frame(i) with ${format === 'u8g2' ? 'u8g2.drawXBMP' : 'display.drawBitmap'}. */
#ifndef ${prefix}_H
#define ${prefix}_H
#include <stdint.h>
#ifdef __AVR__
#include <avr/pgmspace.h>
#endif
#ifndef PROGMEM
#define PROGMEM
#endif
#define ${prefix}_WIDTH ${width}
#define ${prefix}_HEIGHT ${height}
#define ${prefix}_ROW_BYTES ${Math.ceil(width / 8)}
#define ${prefix}_FRAME_BYTES ${frameBytes}
#define ${prefix}_FRAME_COUNT ${frames.length}
#define ${prefix}_FPS ${fps}
#define ${prefix}_DATA_BYTES ${data.length}
#define ${prefix}_STORAGE_BYTES ${data.length}
static const uint8_t ${symbol}_data[] PROGMEM = {
${rows.join(',\n')}
};
static inline const uint8_t *${symbol}_frame(uint32_t i) {
  return i < ${prefix}_FRAME_COUNT ? ${symbol}_data + i * (uint32_t)${prefix}_FRAME_BYTES : (const uint8_t *)0;
}
#endif
`;
  return { header, data, storageBytes: data.length, format };
}

export function rgb565(r, g, b) {
  return ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | ((b & 0xf8) >> 3);
}

// 16-bit RGB565 words for ST7789/SSD1351 TFTs and HUB75 RGB LED matrices.
export function packRGB565(frame, width, height, { fg = rgb565(75, 195, 255), bg = 0x0000, dualTone = false, split = 16, topFg = rgb565(255, 210, 65) } = {}) {
  const words = new Uint16Array(width * height);
  const fb = { width, height, data: frame };
  for (let y = 0; y < height; y++) {
    const onColor = dualTone && y < split ? topFg : fg;
    for (let x = 0; x < width; x++) words[y * width + x] = getPixel(fb, x, y) ? onColor : bg;
  }
  return words;
}

export function buildRGB565Header(sequence, symbol = 'oledfx_animation', options = {}) {
  const { width, height, fps, frames } = validateSequence(sequence);
  validateSymbol(symbol);
  const prefix = symbol.toUpperCase(), frameWords = width * height, frameBytes = frameWords * 2;
  const words = Uint16Array.from(frames.flatMap(frame => Array.from(packRGB565(frame, width, height, options))));
  const storageBytes = words.byteLength;
  const rows = [];
  for (let i = 0; i < words.length; i += 12) rows.push('  ' + Array.from(words.slice(i, i + 12), v => `0x${v.toString(16).padStart(4, '0')}`).join(', '));
  const header = `/* Generated by oledfx: rgb565, 16-bit row-major words.
 * Random-access frames. Use ${symbol}_frame(i) with ST7789 pushImage / HUB75 drawRGBBitmap. */
#ifndef ${prefix}_H
#define ${prefix}_H
#include <stdint.h>
#ifdef __AVR__
#include <avr/pgmspace.h>
#endif
#ifndef PROGMEM
#define PROGMEM
#endif
#define ${prefix}_WIDTH ${width}
#define ${prefix}_HEIGHT ${height}
#define ${prefix}_DEPTH 16
#define ${prefix}_FRAME_WORDS ${frameWords}
#define ${prefix}_FRAME_BYTES ${frameBytes}
#define ${prefix}_FRAME_COUNT ${frames.length}
#define ${prefix}_FPS ${fps}
#define ${prefix}_DATA_BYTES ${storageBytes}
#define ${prefix}_STORAGE_BYTES ${storageBytes}
static const uint16_t ${symbol}_data[] PROGMEM = {
${rows.join(',\n')}
};
static inline const uint16_t *${symbol}_frame(uint32_t i) {
  return i < ${prefix}_FRAME_COUNT ? ${symbol}_data + i * (uint32_t)${prefix}_FRAME_WORDS : (const uint16_t *)0;
}
#endif
`;
  return { header, data: words, storageBytes, format: 'rgb565' };
}

export function buildHeader(sequence, symbol = 'oledfx_animation') {
  validateSequence(sequence);
  validateSymbol(symbol);
  const { width = 128, height = 64, fps = 16, frames } = sequence;
  const encoded = encodeSequence(frames), offsets = [0];
  for (const frame of encoded) offsets.push(offsets.at(-1) + frame.length);
  const data = Uint8Array.from(encoded.flatMap(frame => Array.from(frame)));
  const sizes = encoded.map(frame => frame.length), prefix = symbol.toUpperCase();
  const storageBytes = data.length + 4 * (offsets.length + sizes.length);
  const array = (type, name, values, hex = false) => {
    const rows = [];
    for (let i = 0; i < values.length; i += 16)
      rows.push('  ' + Array.from(values.slice(i, i + 16), value => hex ? `0x${value.toString(16).padStart(2, '0')}` : String(value)).join(', '));
    return `static const ${type} ${symbol}_${name}[] PROGMEM = {\n${rows.join(',\n')}\n};\n`;
  };
  const header = `/* Generated by oledfx. SSD1306 vertical pages; decode in frame order.
 * Start with a zeroed framebuffer; reset before replaying frame 0. */
#ifndef ${prefix}_H
#define ${prefix}_H
#include <stdint.h>
#ifdef __AVR__
#include <avr/pgmspace.h>
#endif
#ifndef PROGMEM
#define PROGMEM
#endif
#define ${prefix}_WIDTH ${width}
#define ${prefix}_HEIGHT ${height}
#define ${prefix}_PAGE_COUNT ${height / 8}
#define ${prefix}_FRAME_BYTES ${width * height / 8}
#define ${prefix}_FRAME_COUNT ${frames.length}
#define ${prefix}_FPS ${fps}
#define ${prefix}_DATA_BYTES ${data.length}
#define ${prefix}_STORAGE_BYTES ${storageBytes}

${array('uint8_t', 'data', data, true)}
${array('uint32_t', 'offsets', offsets)}
${array('uint32_t', 'sizes', sizes)}
${playerSource}
/* Feed sequential indices; frame 0 automatically resets the driver buffer. */
static inline int ${symbol}_step_frame(uint8_t *fb, uint32_t i) {
  if (!fb || i >= ${prefix}_FRAME_COUNT) return 0;
  return oledfx_step_frame(fb, ${prefix}_FRAME_BYTES, ${symbol}_data,
    OLEDFX_READ_U32(${symbol}_offsets + i), OLEDFX_READ_U32(${symbol}_sizes + i), i);
}
#endif
`;
  return { header, data, offsets, sizes, encoded, storageBytes };
}

